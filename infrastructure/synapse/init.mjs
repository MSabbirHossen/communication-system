// One-time Synapse configuration for the local dev environment (cross-platform; no bash).
//
//   node infrastructure/synapse/init.mjs            generate config if missing, append dev overrides
//   node infrastructure/synapse/init.mjs --reset    wipe ./synapse/data and the Mongo volume, then re-init
//
// Lessons from the CI job are encoded here: run the image as the host uid/gid so the
// files stay writable, and start the appended overrides on a fresh line because the
// generated homeserver.yaml has no trailing newline.
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  appendFileSync,
  writeFileSync,
} from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const infra = join(here, "..");
const dataDir = join(here, "data");
const composeFile = join(infra, "docker-compose.yml");
const overridesFile = join(here, "dev-overrides.yaml");
const configFile = join(dataDir, "homeserver.yaml");
const image = "ghcr.io/element-hq/synapse:latest";
const reset = process.argv.includes("--reset");

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, {
    stdio: "inherit",
    shell: false,
    ...opts,
  });

  if (r.error) {
    console.error(`Failed to execute ${cmd}:`, r.error.message);
    process.exit(1);
  }

  if (r.status !== 0) {
    console.error(`${cmd} ${args.join(" ")} failed (exit ${r.status ?? "signal"})`);
    process.exit(r.status ?? 1);
  }
}

const docker = spawnSync("docker", ["version", "--format", "{{.Server.Version}}"], {
  encoding: "utf8",
  shell: false,
});

if (docker.error || docker.status !== 0) {
  console.error(
    "Docker is not available. Start Docker Desktop and make sure `docker version` works.",
  );
  process.exit(1);
}

console.log(`docker server ${docker.stdout.trim()}`);

if (reset) {
  console.log("reset: stopping services and removing Synapse data and the MongoDB volume");
  run("docker", ["compose", "-f", composeFile, "down", "--volumes"]);
  rmSync(dataDir, { recursive: true, force: true });
}

mkdirSync(dataDir, { recursive: true });

// uid/gid for the container (Linux/macOS: current user; Windows/Docker Desktop: defaults are fine).
const uid = typeof process.getuid === "function" ? String(process.getuid()) : "1000";
const gid = typeof process.getgid === "function" ? String(process.getgid()) : "1000";
const envFile = join(infra, ".env");
writeFileSync(
  envFile,
  `# generated by synapse/init.mjs; safe to commit? No: it is git-ignored.\nUID=${uid}\nGID=${gid}\n`,
);

if (existsSync(configFile)) {
  console.log(
    `config already exists at ${configFile}; nothing to generate (use --reset to start over)`,
  );
} else {
  console.log("generating Synapse configuration (server_name=localhost, report_stats=no)");
  run("docker", [
    "run",
    "--rm",
    "-v",
    `${dataDir}:/data`,
    "-e",
    "SYNAPSE_SERVER_NAME=localhost",
    "-e",
    "SYNAPSE_REPORT_STATS=no",
    "-e",
    `UID=${uid}`,
    "-e",
    `GID=${gid}`,
    image,
    "generate",
  ]);
  const overrides = readFileSync(overridesFile, "utf8");
  appendFileSync(configFile, `\n${overrides}`);
  console.log(
    "appended dev-overrides.yaml (open registration, relaxed rate limits — development only)",
  );
}

const cfg = readFileSync(configFile, "utf8");
if (!/^enable_registration: true$/m.test(cfg)) {
  console.error(
    "homeserver.yaml does not contain `enable_registration: true` on its own line; check the append step",
  );
  process.exit(1);
}
console.log(
  "ready. Next: `pnpm dev:env` then `curl http://localhost:8008/_matrix/client/versions`",
);
